#!/usr/bin/env python3
"""
emit_remotion.py
Reads motion_blueprint.json and scaffolds a modular Remotion (React + TypeScript) project.
Remotion is treated as the first-class compile target.
"""

import argparse
import json
import os
import sys
from pathlib import Path


def emit_remotion_project(blueprint_path, out_dir):
    with open(blueprint_path, "r", encoding="utf-8") as f:
        bp = json.load(f)
        
    out_dir = Path(out_dir)
    scenes_dir = out_dir / "scenes"
    components_dir = out_dir / "components"
    scenes_dir.mkdir(parents=True, exist_ok=True)
    components_dir.mkdir(parents=True, exist_ok=True)
    
    meta = bp.get("meta", {})
    tokens = bp.get("design_tokens", {})
    palette = tokens.get("palette", {})
    typography = tokens.get("typography", {})
    scenes = bp.get("scenes", [])
    
    width = meta.get("resolution", {}).get("width", 1920)
    height = meta.get("resolution", {}).get("height", 1080)
    fps = meta.get("fps", 60)
    total_frames = meta.get("total_frames", 720)
    
    # 1. Emit constants.ts
    constants_content = f"""// Auto-generated by motion-video-deconstruct from {meta.get('source_file', 'reference')}
export const VIDEO_CONFIG = {{
  width: {width},
  height: {height},
  fps: {fps},
  totalFrames: {total_frames},
  bpm: {meta.get('bpm', 120)},
}};

export const THEME = {{
  background: '{palette.get('background', '#0b0c10')}',
  surface: '{palette.get('surface', '#141721')}',
  border: '{palette.get('border', 'rgba(255, 255, 255, 0.08)')}',
  textPrimary: '{palette.get('text_primary', '#ffffff')}',
  textSecondary: '{palette.get('text_secondary', '#717e94')}',
  accent: '{palette.get('accent', '#00f0ff')}',
  safeMargin: {tokens.get('safe_margin_px', 64)},
}};

export const TYPOGRAPHY = {{
  headlineFont: '{typography.get('headline_font', 'Inter, -apple-system, sans-serif')}',
  monoFont: '{typography.get('mono_font', 'JetBrains Mono, monospace')}',
}};
"""
    with open(out_dir / "constants.ts", "w", encoding="utf-8") as f:
        f.write(constants_content)
        
    # 2. Emit Scene components
    scene_imports = []
    scene_sequences = []
    
    for idx, sc in enumerate(scenes):
        scene_name = f"Scene{idx+1:02d}"
        dur_frames = sc.get("timeline", {}).get("duration_frames", 180)
        scene_imports.append(f"import {{ {scene_name} }} from './scenes/{scene_name}';")
        scene_sequences.append(f"      <Series.Sequence durationInFrames={{{dur_frames}}}>\n        <{scene_name} />\n      </Series.Sequence>")
        
        scene_tsx = f"""import React from 'react';
import {{ interpolate, spring, useCurrentFrame, useVideoConfig }} from 'remotion';
import {{ THEME, TYPOGRAPHY }} from '../constants';

export const {scene_name}: React.FC = () => {{
  const frame = useCurrentFrame();
  const {{ fps }} = useVideoConfig();

  // Entrance spring physics
  const enterSpring = spring({{
    frame,
    fps,
    config: {{ mass: 1.0, stiffness: 140, damping: 14 }},
  }});

  const cardTranslateY = interpolate(enterSpring, [0, 1], [60, 0]);
  const cardOpacity = interpolate(enterSpring, [0, 1], [0, 1]);

  return (
    <div
      style={{{{
        width: '100%',
        height: '100%',
        backgroundColor: THEME.background,
        display: 'flex',
        padding: THEME.safeMargin,
        boxSizing: 'border-box',
        gap: '24px',
        position: 'relative',
        overflow: 'hidden',
      }}}}
    >
      {{/* Main Stage Ground */}}
      <div
        style={{{{
          flex: '7',
          backgroundColor: THEME.surface,
          border: `1px solid ${{THEME.border}}`,
          borderRadius: '16px',
          padding: '48px',
          display: 'flex',
          flexDirection: 'column',
          justifyContent: 'space-between',
          transform: `translateY(${{cardTranslateY}}px)`,
          opacity: cardOpacity,
          boxShadow: '0 24px 64px rgba(0,0,0,0.4)',
        }}}}
      >
        <div>
          <div
            style={{{{
              fontFamily: TYPOGRAPHY.monoFont,
              fontSize: '14px',
              color: THEME.accent,
              letterSpacing: '0.1em',
              marginBottom: '16px',
              textTransform: 'uppercase',
            }}}}
          >
            ACT // {idx+1:02d} — {sc.get('name', 'SCENE')}
          </div>
          <h1
            style={{{{
              fontFamily: TYPOGRAPHY.headlineFont,
              fontSize: '52px',
              fontWeight: 700,
              color: THEME.textPrimary,
              margin: 0,
              lineHeight: 1.15,
            }}}}
          >
            Deterministic Motion Design
          </h1>
        </div>

        {{/* Dynamic Telemetry Footer */}}
        <div
          style={{{{
            display: 'flex',
            justifyContent: 'space-between',
            alignItems: 'center',
            borderTop: `1px solid ${{THEME.border}}`,
            paddingTop: '20px',
            fontFamily: TYPOGRAPHY.monoFont,
            fontSize: '13px',
            color: THEME.textSecondary,
          }}}}
        >
          <span>FRAME: {{frame.toString().padStart(4, '0')}}</span>
          <span style={{{{ color: THEME.accent }}}}>STATUS: ACTIVE</span>
        </div>
      </div>

      {{/* Telemetry Sidebar */}}
      <div
        style={{{{
          flex: '3',
          backgroundColor: THEME.surface,
          border: `1px solid ${{THEME.border}}`,
          borderRadius: '16px',
          padding: '32px',
          display: 'flex',
          flexDirection: 'column',
          justifyContent: 'space-between',
        }}}}
      >
        <div style={{{{ fontFamily: TYPOGRAPHY.monoFont, fontSize: '13px', color: THEME.textSecondary }}}}>
          <div>FPS: {fps}</div>
          <div style={{{{ marginTop: '8px' }}}}>DUR: {dur_frames}f</div>
          <div style={{{{ marginTop: '8px', color: THEME.accent }}}}>ACCENT: {palette.get('accent', '#00f0ff')}</div>
        </div>
      </div>
    </div>
  );
}};
"""
        with open(scenes_dir / f"{scene_name}.tsx", "w", encoding="utf-8") as f:
            f.write(scene_tsx)
            
    # 3. Emit Root.tsx
    root_tsx = f"""import React from 'react';
import {{ Composition, Series }} from 'remotion';
import {{ VIDEO_CONFIG }} from './constants';
{chr(10).join(scene_imports)}

export const MainVideo: React.FC = () => {{
  return (
    <Series>
{chr(10).join(scene_sequences)}
    </Series>
  );
}};

export const RemotionRoot: React.FC = () => {{
  return (
    <Composition
      id="DeconstructedMotionVideo"
      component={{MainVideo}}
      durationInFrames={{VIDEO_CONFIG.totalFrames}}
      fps={{VIDEO_CONFIG.fps}}
      width={{VIDEO_CONFIG.width}}
      height={{VIDEO_CONFIG.height}}
    />
  );
}};
"""
    with open(out_dir / "Root.tsx", "w", encoding="utf-8") as f:
        f.write(root_tsx)
        
    print(f"[+] Successfully emitted Remotion scaffold to: {out_dir}")
    print(f"[+] Created Root.tsx, constants.ts, and {len(scenes)} scene components.")


def main():
    parser = argparse.ArgumentParser(description="Emit Remotion project from motion_blueprint.json")
    parser.add_argument("--blueprint", "-b", required=True, help="Path to motion_blueprint.json")
    parser.add_argument("--out-dir", "-o", default="src", help="Output directory for TSX files")
    args = parser.parse_args()
    
    if not os.path.exists(args.blueprint):
        print(f"Error: blueprint '{args.blueprint}' not found.", file=sys.stderr)
        sys.exit(1)
        
    emit_remotion_project(args.blueprint, args.out_dir)


if __name__ == "__main__":
    main()
